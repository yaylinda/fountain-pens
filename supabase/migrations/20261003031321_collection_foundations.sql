-- Deferred cross-table invariant, including old parent when a privileged link moves.
create function private.check_event_links() returns trigger language plpgsql set search_path = '' as $$
declare target text; targets text[]; event_kind text; n bigint; low integer; high integer;
begin
 if tg_table_name = 'refill_events' then
  if tg_op <> 'DELETE' then targets := array[new.id]; end if;
 else
  if tg_op <> 'INSERT' then targets := array[old.event_id]; end if;
  if tg_op <> 'DELETE' then targets := array_append(targets,new.event_id); end if;
 end if;
 foreach target in array coalesce(targets,array[]::text[]) loop
  select kind into event_kind from public.refill_events where id=target;
  if not found then continue; end if;
  select count(*),min(position),max(position) into n,low,high from public.refill_event_inks where event_id=target;
  if (event_kind='cleaning' and n<>0) or
     (event_kind='refill' and (n=0 or low<>0 or high<>n-1)) then
   raise exception 'invalid event links' using errcode='23514';
  end if;
 end loop;
 return null;
end $$;
revoke all on function private.check_event_links() from public, anon, authenticated;
create constraint trigger event_links_valid after insert or update or delete on public.refill_events
 deferrable initially deferred for each row execute function private.check_event_links();
create constraint trigger event_links_valid after insert or update or delete on public.refill_event_inks
 deferrable initially deferred for each row execute function private.check_event_links();

-- Canonical digest is SHA256 of UTF8 PostgreSQL jsonb::text for this versioned command.
-- All commands and imports share advisory lock (17012026,1), acquired before row reads.
create function private.set_pen_queue(p_request_id uuid, p_pen_id text, p_expected_version bigint, p_needs_refill boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_owner uuid := auth.uid(); v_hash text; receipt private.mutation_receipts; pen public.pens; answer jsonb;
begin
 if v_owner is null or not private.is_owner() then raise exception 'forbidden' using errcode='42501'; end if;
 if p_request_id is null or p_pen_id is null or p_pen_id='' or p_expected_version is null or p_expected_version<1 or p_needs_refill is null then
  raise exception 'validation' using errcode='22023';
 end if;
 perform pg_catalog.pg_advisory_xact_lock(17012026,1);
 v_hash := encode(sha256(convert_to(jsonb_build_array('set_pen_queue/v1',p_pen_id,p_expected_version::text,p_needs_refill)::text,'UTF8')),'hex');
 select * into receipt from private.mutation_receipts where owner_id=v_owner and request_id=p_request_id;
 if found then
  if receipt.command<>'set_pen_queue/v1' or receipt.payload_sha256<>v_hash then raise exception 'request conflict' using errcode='40001'; end if;
  return receipt.result;
 end if;
 select * into pen from public.pens where id=p_pen_id and owner_id=v_owner for update;
 if not found then raise exception 'not found' using errcode='P0002'; end if;
 if pen.version<>p_expected_version then raise exception 'version conflict' using errcode='40001'; end if;
 -- A semantic no-op keeps the version, while still recording a durable retry receipt.
 if pen.needs_refill<>p_needs_refill then
  update public.pens set needs_refill=p_needs_refill,version=version+1,updated_at=now()
   where id=p_pen_id and owner_id=v_owner returning * into pen;
 end if;
 answer := jsonb_build_object('id',pen.id,'version',pen.version::text,'needsRefill',pen.needs_refill);
 insert into private.mutation_receipts(owner_id,request_id,command,payload_sha256,result)
 values(v_owner,p_request_id,'set_pen_queue/v1',v_hash,answer);
 return answer;
end $$;
alter function private.set_pen_queue(uuid,text,bigint,boolean) owner to collection_writer;
revoke all on function private.set_pen_queue(uuid,text,bigint,boolean) from public,anon,authenticated;
grant execute on function private.set_pen_queue(uuid,text,bigint,boolean) to authenticated;
create function public.set_pen_queue(p_request_id uuid,p_pen_id text,p_expected_version bigint,p_needs_refill boolean)
returns jsonb language sql security invoker set search_path = '' as $$
 select private.set_pen_queue(p_request_id,p_pen_id,p_expected_version,p_needs_refill)
$$;
