-- Local review candidate. No owner, Auth user, Storage bucket, or production data is provisioned.
create schema private;
revoke all on schema private from public, anon, authenticated;
revoke create on schema public from public, anon, authenticated;
create role collection_writer nologin nosuperuser nocreatedb nocreaterole noinherit nobypassrls;
grant usage on schema public, private, auth to collection_writer;
grant execute on function auth.uid() to collection_writer;
alter default privileges in schema public revoke execute on functions from public;
alter default privileges in schema private revoke execute on functions from public;

create table private.collection_owner (
 singleton boolean primary key default true check (singleton),
 user_id uuid not null unique references auth.users(id) on delete restrict,
 time_zone text not null check (time_zone = 'America/Chicago')
);
create table private.data_imports (
 id text primary key check (id <> ''),
 owner_id uuid not null references private.collection_owner(user_id),
 source_sha256 text not null check (source_sha256 ~ '^[0-9a-f]{64}$'),
 mapping_version text not null,
 manifest jsonb not null check (jsonb_typeof(manifest) = 'object'),
 imported_at timestamptz not null default now()
);
create table private.mutation_receipts (
 owner_id uuid not null references private.collection_owner(user_id),
 request_id uuid not null,
 command text not null,
 payload_sha256 text not null check (payload_sha256 ~ '^[0-9a-f]{64}$'),
 result jsonb not null check (jsonb_typeof(result) = 'object'),
 created_at timestamptz not null default now(),
 primary key (owner_id, request_id)
);
create table public.pens (
 id text primary key default gen_random_uuid()::text check (id <> ''),
 owner_id uuid not null references private.collection_owner(user_id) on delete restrict,
 brand text not null, model text not null, color text not null, nib_size text not null, nib_type text not null, archived boolean not null default false, favorite boolean not null default false, needs_refill boolean not null default false,
 version bigint not null default 1 check (version > 0),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique (owner_id, id)
);
create table public.inks (
 id text primary key default gen_random_uuid()::text check (id <> ''),
 owner_id uuid not null references private.collection_owner(user_id) on delete restrict,
 brand text not null, collection text not null default '', name text not null, color_hex text check (color_hex ~ '^#[0-9A-Fa-f]{6}$'), archived boolean not null default false, favorite boolean not null default false, check (id <> 'NONE'),
 version bigint not null default 1 check (version > 0),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique (owner_id, id)
);
create table public.refill_events (
 id text primary key default gen_random_uuid()::text check (id <> ''),
 owner_id uuid not null references private.collection_owner(user_id) on delete restrict,
 pen_id text not null, occurred_on date not null, kind text not null check (kind in ('refill','cleaning')), notes text not null default '', not_pure boolean not null default false, sequence bigint generated by default as identity unique check (sequence > 0), foreign key (owner_id,pen_id) references public.pens(owner_id,id) on delete restrict, check (kind <> 'cleaning' or not not_pure),
 version bigint not null default 1 check (version > 0),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique (owner_id, id)
);
create table public.refill_event_inks (
 owner_id uuid not null,
 event_id text not null,
 ink_id text not null,
 position integer not null check (position >= 0),
 primary key (event_id,ink_id), unique (event_id,position),
 foreign key (owner_id,event_id) references public.refill_events(owner_id,id) on delete cascade,
 foreign key (owner_id,ink_id) references public.inks(owner_id,id) on delete restrict
);
create index refill_pen_history on public.refill_events(owner_id,pen_id,occurred_on desc,sequence desc);
create index refill_journal on public.refill_events(owner_id,occurred_on desc,sequence desc);
create index refill_ink_history on public.refill_event_inks(owner_id,ink_id,event_id);

